"""The bundled example predictions match what the pinned risearch produces.

`examples/data/predictions.out` is generated by
`examples/generate_example_data.py`. A risearch bump that changes search
results makes it stale, and the README's quick start (pre-computed
predictions) and full example (in-process search) stop agreeing. Regenerate
with `python examples/generate_example_data.py` when this fails.
"""

from pathlib import Path

from polars.testing import assert_frame_equal

import sioff
from sioff.services.risearch_parser import RIsearchParser

DATA = Path(__file__).resolve().parents[2] / "examples" / "data"
KEY = ["sirna_id", "chrom", "start", "end", "strand", "energy"]


def test_bundled_predictions_match_a_fresh_search(tmp_path: Path) -> None:
    idx = sioff.index(DATA / "genome.fa", output=tmp_path / "genome.idx")
    fresh = sioff.search(DATA / "sirnas.fa", idx, target=DATA / "genome.fa")
    bundled = RIsearchParser().load(DATA / "predictions.out")

    fresh = fresh.select(bundled.columns).cast(bundled.schema).sort(KEY)
    assert_frame_equal(bundled.sort(KEY), fresh, abs_tol=1e-4, check_exact=False)
